// Real local workerd + SQLite Durable Object + R2. GitHub egress is mocked.
// No Cloudflare/GitHub account or live issue is used by this test.
import {Miniflare, Response as LocalResponse, convertV4MiniflareOptions} from 'miniflare';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const origin='https://shellshifter-reports.example.workers.dev';
const requestFile=process.argv[2];
if(!requestFile) throw new Error('Pass a report_contract_237_YEAR.json generated by the Maya tests.');
const report=JSON.parse(readFileSync(requestFile,'utf8'));
let githubCalls=0, issueBody='';
const mf=new Miniflare(convertV4MiniflareOptions({modules:true,scriptPath:fileURLToPath(new URL('worker.mjs',import.meta.url)),
  compatibilityDate:'2026-10-14',cf:false,stripCfConnectingIp:false,
  bindings:{PUBLIC_ORIGIN:origin,REPORTS_ENABLED:'true',GITHUB_TOKEN:'local-test-not-a-real-token',LINK_SECRET:'a'.repeat(64)},
  durableObjects:{QUOTA:{className:'ReportQuota',useSQLite:true}},r2Buckets:['IMAGES'],
  ratelimits:{INTAKE_LIMIT:{namespace_id:'23701',simple:{limit:5,period:60}},
    IMAGE_LIMIT:{namespace_id:'23702',simple:{limit:60,period:60}}},
  outboundService:async request=>{
    assert.equal(request.url,'https://api.github.com/repos/skazochnik3d/ShellShifter/issues');
    assert.equal(request.headers.get('Authorization'),'Bearer local-test-not-a-real-token');
    githubCalls++;issueBody=(await request.json()).body;
    return new LocalResponse(JSON.stringify({html_url:'https://github.com/skazochnik3d/ShellShifter/issues/123'}),{status:201});
  }}));
try {
  const health=await mf.dispatchFetch(origin+'/health');assert.equal((await health.json()).enabled,true);
  for(let n=0;n<2;n++) {
    const res=await mf.dispatchFetch(origin+'/v1/reports',{method:'POST',headers:{
      'Content-Type':'application/json','CF-Connecting-IP':'198.51.100.5'},body:JSON.stringify(report)});
    const body=await res.json();assert.equal(res.status,201,JSON.stringify(body));
    assert.equal(body.issue_url,'https://github.com/skazochnik3d/ShellShifter/issues/123');
  }
  assert.equal(githubCalls,1);
  assert.ok(!issueBody.includes('private/client'));
  const url=/!\[Screenshot\]\(([^)]+)\)/.exec(issueBody)[1];
  const image=await mf.dispatchFetch(url,{headers:{'CF-Connecting-IP':'198.51.100.5'}});
  assert.equal(image.status,200);assert.equal(image.headers.get('Content-Type'),'image/png');
  assert.deepEqual(Buffer.from(await image.arrayBuffer()).subarray(0,8),Buffer.from([137,80,78,71,13,10,26,10]));
  const forged=new URL(url);forged.searchParams.set('key','x');
  assert.equal((await mf.dispatchFetch(forged,{headers:{'CF-Connecting-IP':'198.51.100.5'}})).status,404);
  console.log('PASS: Maya-produced PNG → real local workerd → SQLite quota → R2 → mocked GitHub; retry creates one issue.');
} finally {await mf.dispose();}
